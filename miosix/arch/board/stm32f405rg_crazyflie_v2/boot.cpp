#include <interfaces-impl/bsp_impl.h>
#include <interfaces/delays.h>

extern "C" void SystemInit();

namespace miosix {

void IRQmemoryAndClockInit()
{
    // Currently we use the code provided by ST (with our modifications) to
    // handle the memory and clock initialization process.
    SystemInit();

    //Enable all gpios
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN | RCC_AHB1ENR_GPIOBEN |
                    RCC_AHB1ENR_GPIOCEN | RCC_AHB1ENR_GPIODEN |
                    RCC_AHB1ENR_GPIOEEN | RCC_AHB1ENR_GPIOHEN;
    RCC_SYNC();
    GPIOA->OSPEEDR=0xaaaaaaaa; //Default to 50MHz speed for all GPIOS
    GPIOB->OSPEEDR=0xaaaaaaaa;
    GPIOC->OSPEEDR=0xaaaaaaaa;
    GPIOD->OSPEEDR=0xaaaaaaaa;
    GPIOE->OSPEEDR=0xaaaaaaaa;
    GPIOH->OSPEEDR=0xaaaaaaaa;

    // Initialize board leds
    _led_red_l::mode(Mode::OUTPUT);
    _led_green_l::mode(Mode::OUTPUT);
    _led_green_r::mode(Mode::OUTPUT);
    _led_red_r::mode(Mode::OUTPUT);
    _led_blue_l::mode(Mode::OUTPUT);
}

} // namespace miosix
